export const vocabulary: VocabItem[] = RAW_LESSONS.flatMap((lesson) =>
  lesson.entries.map((word, index) => ({
    id: `L${lesson.number}-${index + 1}`,
    lesson: lesson.number,
    japanese: word[0],
    bengali: word[1],
  })),
);

export interface LessonMeta {
  number: number;
  wordCount: number;
  estimatedMinutes: number;
}

export const lessonList: LessonMeta[] = RAW_LESSONS.map((lesson) => ({
  number: lesson.number,
  wordCount: lesson.entries.length,
  estimatedMinutes: Math.max(
    4,
    Math.round(lesson.entries.length * 0.32) + 2,
  ),
}));

export const vocabByLesson: Record<number, VocabItem[]> =
  lessonList.reduce((acc, lesson) => {
    acc[lesson.number] = vocabulary.filter(
      (word) => word.lesson === lesson.number,
    );
    return acc;
  }, {} as Record<number, VocabItem[]>);

export function getVocabById(id: string): VocabItem | undefined {
  return vocabulary.find((word) => word.id === id);
}

